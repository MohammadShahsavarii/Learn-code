'''
<       less than
>       greater than
<=      less than and equal to
>=      greater than and equal to
==      equal
!=      not equal
'''

print( 3 < 5)   # True
print( 8 > 7)   # True
print( 6 > 8)   # False
print(4 <= 3)   # False
print(4 <= 5)   # True
print(3 >= 2)   # True
print(2 == 2)   # True
print(3 != 2)   # True
print(2 != 2)   # False

print("mina" == "bita")     # False
